package io.github.ignat22.textlab.bench;

import io.github.ignat22.textlab.chart.SvgLineChart;
import io.github.ignat22.textlab.dp.EditDistanceSolver;
import io.github.ignat22.textlab.dp.LcsSolver;
import io.github.ignat22.textlab.search.KmpSearcher;
import io.github.ignat22.textlab.search.NaiveSearcher;
import io.github.ignat22.textlab.search.PatternSearcher;
import io.github.ignat22.textlab.search.RabinKarpSearcher;
import io.github.ignat22.textlab.search.SearchReport;
import io.github.ignat22.textlab.suffix.KasaiLcp;
import io.github.ignat22.textlab.suffix.LcpResult;
import io.github.ignat22.textlab.suffix.SuffixArrays;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

public final class BenchmarkSuite {

    public static final int[] DP_SIZES = {100, 500, 1_000};
    public static final int[] TEXT_SIZES = {10_000, 50_000, 100_000};
    public static final int[] KASAI_SIZES = {1_000, 5_000, 10_000};
    public static final int RANDOM_PATTERN_LENGTH = 16;
    public static final int FIBONACCI_PATTERN_LENGTH = 40;

    private final Path resultsDir;
    private final Path plotsDir;
    private final List<PatternSearcher> searchers = List.of(new NaiveSearcher(), new KmpSearcher(), new RabinKarpSearcher());
    private final StringBuilder report = new StringBuilder();

    public BenchmarkSuite(Path resultsDir, Path plotsDir) {
        this.resultsDir = resultsDir;
        this.plotsDir = plotsDir;
    }

    public void runAll() throws IOException {
        report.append("# Experimental results\n\n")
                .append("Generated by `java -jar text-algorithms-lab.jar bench` on ").append(LocalDate.now()).append(".\n\n")
                .append("- Java: ").append(System.getProperty("java.vm.name")).append(' ').append(System.getProperty("java.version")).append('\n')
                .append("- OS: ").append(System.getProperty("os.name")).append(' ').append(System.getProperty("os.arch"))
                .append(", logical CPUs: ").append(Runtime.getRuntime().availableProcessors()).append('\n')
                .append("- Seed: ").append(Workloads.SEED).append(", alphabet: `").append(Workloads.ALPHABET).append("`\n")
                .append("- Warm-up runs: ").append(Stopwatch.WARMUP_RUNS).append(", timed runs: ").append(Stopwatch.TIMED_RUNS).append(" (mean ± sample std. dev.)\n\n");
        warmUpJit();
        dynamicProgramming();
        stringMatching("random", "random a-z text", this::randomScenarios, RANDOM_PATTERN_LENGTH);
        stringMatching("fibonacci", "Fibonacci word over {a,b}", this::fibonacciScenarios, FIBONACCI_PATTERN_LENGTH);
        kasai();
        Files.createDirectories(resultsDir);
        Files.writeString(resultsDir.resolve("RESULTS.md"), report.toString(), StandardCharsets.UTF_8);
        System.out.println("Wrote " + resultsDir.resolve("RESULTS.md"));
    }

    private void warmUpJit() {
        System.out.println("Warming up the JIT...");
        Workloads w = new Workloads(1);
        String a = w.randomText(400);
        String b = w.randomText(400);
        String text = w.randomText(20_000);
        String pattern = text.substring(7_000, 7_016);
        String fibonacci = Workloads.fibonacciWord(20_000);
        String fibonacciPattern = fibonacci.substring(0, FIBONACCI_PATTERN_LENGTH);
        String shortText = text.substring(0, 3_000);
        String shortFibonacci = fibonacci.substring(0, 3_000);
        int[] sa = SuffixArrays.byPrefixDoubling(shortText);
        int[] fibonacciSa = SuffixArrays.byPrefixDoubling(shortFibonacci);
        for (int i = 0; i < 100; i++) {
            LcsSolver.length(a, b);
            EditDistanceSolver.distance(a, b);
            for (PatternSearcher s : searchers) {
                s.search(text, pattern);
                s.search(fibonacci, fibonacciPattern);
            }
            KasaiLcp.build(shortText, sa);
            KasaiLcp.build(shortFibonacci, fibonacciSa);
        }
    }

    private void dynamicProgramming() throws IOException {
        System.out.println("Experiment 1: LCS and Edit Distance");
        ResultTable table = new ResultTable("n=m", "cells", "LCS ms", "LCS sd", "LCS ns/cell", "LCS length",
                "ED ms", "ED sd", "ED ns/cell", "edit distance");
        Workloads w = new Workloads(Workloads.SEED);
        double[] x = new double[DP_SIZES.length];
        double[] lcsMs = new double[DP_SIZES.length];
        double[] edMs = new double[DP_SIZES.length];
        for (int k = 0; k < DP_SIZES.length; k++) {
            int n = DP_SIZES[k];
            String a = w.randomText(n);
            String b = w.randomText(n);
            long cells = (long) n * n;
            Stopwatch.Timed<Integer> lcs = Stopwatch.measure(() -> LcsSolver.length(a, b));
            Stopwatch.Timed<Integer> ed = Stopwatch.measure(() -> EditDistanceSolver.distance(a, b));
            table.row(n, cells, lcs.measurement().meanMillis(), lcs.measurement().stdevMillis(),
                    lcs.measurement().meanNanos() / cells, lcs.result(),
                    ed.measurement().meanMillis(), ed.measurement().stdevMillis(),
                    ed.measurement().meanNanos() / cells, ed.result());
            x[k] = n;
            lcsMs[k] = lcs.measurement().meanMillis();
            edMs[k] = ed.measurement().meanMillis();
        }
        table.writeCsv(resultsDir.resolve("dp.csv"));
        report.append("## 1. Dynamic programming (two random strings of equal length)\n\n").append(table.toMarkdown()).append('\n');
        new SvgLineChart("LCS and Edit Distance: running time",
                "Two random a-z strings of length n each; mean of 5 timed runs", "string length n (= m)", "time, ms")
                .add("LCS", x, lcsMs)
                .add("Edit Distance", x, edMs)
                .writeTo(plotsDir.resolve("dp-time.svg"));
    }

    private record Scenario(String label, String text, String pattern) {
    }

    private interface ScenarioFactory {
        List<Scenario> build(int n, Workloads w);
    }

    private List<Scenario> randomScenarios(int n, Workloads w) {
        String text = w.randomText(n);
        String present = text.substring(n / 2, n / 2 + RANDOM_PATTERN_LENGTH);
        String absent = w.patternAbsentFrom(text, RANDOM_PATTERN_LENGTH);
        return List.of(new Scenario("present", text, present), new Scenario("absent", text, absent));
    }

    private List<Scenario> fibonacciScenarios(int n, Workloads w) {
        String text = Workloads.fibonacciWord(n);
        String present = text.substring(0, FIBONACCI_PATTERN_LENGTH);
        String absent = text.substring(0, FIBONACCI_PATTERN_LENGTH - 2) + "bb";
        return List.of(new Scenario("present", text, present), new Scenario("absent", text, absent));
    }

    private void stringMatching(String key, String description, ScenarioFactory factory, int patternLength) throws IOException {
        System.out.println("Experiment 2: string matching on " + description);
        ResultTable table = new ResultTable("text n", "pattern", "algorithm", "mean us", "sd us", "matches",
                "scan comparisons", "comparisons / n", "setup comparisons", "hash hits", "spurious hits");
        Workloads w = new Workloads(Workloads.SEED + 1);
        Map<String, double[]> timesPresent = new LinkedHashMap<>();
        Map<String, double[]> timesAbsent = new LinkedHashMap<>();
        for (PatternSearcher s : searchers) {
            timesPresent.put(s.name(), new double[TEXT_SIZES.length]);
            timesAbsent.put(s.name(), new double[TEXT_SIZES.length]);
        }
        double[] x = new double[TEXT_SIZES.length];
        for (int k = 0; k < TEXT_SIZES.length; k++) {
            int n = TEXT_SIZES[k];
            x[k] = n / 1_000.0;
            for (Scenario scenario : factory.build(n, w)) {
                List<Integer> reference = null;
                for (PatternSearcher searcher : searchers) {
                    Stopwatch.Timed<SearchReport> timed = Stopwatch.measure(() -> searcher.search(scenario.text(), scenario.pattern()));
                    SearchReport r = timed.result();
                    if (reference == null) {
                        reference = r.positions();
                    } else if (!reference.equals(r.positions())) {
                        throw new IllegalStateException(searcher.name() + " disagrees with Naive on " + key + " n=" + n);
                    }
                    long scan = r.counters().scanComparisons();
                    table.row(n, scenario.label(), searcher.name(), timed.measurement().meanMicros(),
                            timed.measurement().stdevMicros(), r.occurrences(), scan, (double) scan / n,
                            r.counters().setupComparisons(),
                            searcher instanceof RabinKarpSearcher ? r.counters().hashHits() : "-",
                            searcher instanceof RabinKarpSearcher ? r.counters().spuriousHits() : "-");
                    Map<String, double[]> target = scenario.label().equals("present") ? timesPresent : timesAbsent;
                    target.get(searcher.name())[k] = timed.measurement().meanMicros();
                }
            }
        }
        table.writeCsv(resultsDir.resolve("matching-" + key + ".csv"));
        report.append("## 2. String matching: ").append(description).append(" (m = ").append(patternLength).append(")\n\n")
                .append(table.toMarkdown()).append('\n');
        writeMatchingChart(key, description, patternLength, "present", x, timesPresent);
        writeMatchingChart(key, description, patternLength, "absent", x, timesAbsent);
    }

    private void writeMatchingChart(String key, String description, int m, String label, double[] x,
                                    Map<String, double[]> times) throws IOException {
        SvgLineChart chart = new SvgLineChart(
                "Pattern " + label + ": Naive vs KMP vs Rabin-Karp",
                description + ", pattern length m = " + m + "; mean of 5 timed runs",
                "text length n, thousands of characters", "time, microseconds");
        for (Map.Entry<String, double[]> e : times.entrySet()) {
            chart.add(e.getKey(), x, e.getValue());
        }
        chart.writeTo(plotsDir.resolve("matching-" + key + "-" + label + ".svg"));
    }

    private void kasai() throws IOException {
        System.out.println("Experiment 3: Kasai LCP array");
        ResultTable table = new ResultTable("n", "input", "mean us", "sd us", "comparisons", "comparisons / n",
                "max LCP", "avg LCP");
        Workloads w = new Workloads(Workloads.SEED + 2);
        double[] x = new double[KASAI_SIZES.length];
        List<double[]> series = new ArrayList<>();
        series.add(new double[KASAI_SIZES.length]);
        series.add(new double[KASAI_SIZES.length]);
        for (int k = 0; k < KASAI_SIZES.length; k++) {
            int n = KASAI_SIZES[k];
            x[k] = n / 1_000.0;
            String[] inputs = {w.randomText(n), Workloads.fibonacciWord(n)};
            String[] names = {"random a-z", "Fibonacci word"};
            for (int i = 0; i < inputs.length; i++) {
                String s = inputs[i];
                int[] sa = SuffixArrays.byPrefixDoubling(s);
                Stopwatch.Timed<LcpResult> timed = Stopwatch.measure(() -> KasaiLcp.build(s, sa));
                LcpResult r = timed.result();
                table.row(n, names[i], timed.measurement().meanMicros(), timed.measurement().stdevMicros(),
                        r.comparisons(), (double) r.comparisons() / n, r.max(), r.average());
                series.get(i)[k] = timed.measurement().meanMicros();
            }
        }
        table.writeCsv(resultsDir.resolve("kasai.csv"));
        report.append("## 3. Kasai LCP construction (suffix array built beforehand, not timed)\n\n")
                .append(table.toMarkdown()).append('\n');
        new SvgLineChart("Kasai LCP array: running time",
                "Suffix array prepared outside the timed region; mean of 5 timed runs",
                "string length n, thousands of characters", "time, microseconds")
                .add("random a-z", x, series.get(0))
                .add("Fibonacci word", x, series.get(1))
                .writeTo(plotsDir.resolve("kasai-time.svg"));
    }
}
